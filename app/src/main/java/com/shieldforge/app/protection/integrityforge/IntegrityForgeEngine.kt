package com.shieldforge.app.protection.integrityforge

import com.shieldforge.app.core.common.EngineExecutionResult
import com.shieldforge.app.core.common.EngineExecutionState
import com.shieldforge.app.core.common.LogLevel
import com.shieldforge.app.core.common.ProtectionModuleId
import com.shieldforge.app.core.crypto.CryptoEngine
import com.shieldforge.app.protection.ProtectionPipelineContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import java.util.zip.ZipFile

@Serializable
data class IntegritySealPayload(
    val packageName: String,
    val versionCode: Long,
    val profileName: String,
    val createdAtMs: Long,
    val manifestSha256: String,
    val arscSha256: String,
    val dexSha256Map: Map<String, String>,
    val signingCertSha256: String,
)

object IntegrityForgeEngine {
    private val json = Json { prettyPrint = true }

    fun executeOnApk(ctx: ProtectionPipelineContext): EngineExecutionResult {
        val start = System.currentTimeMillis()
        val moduleId = ProtectionModuleId.INTEGRITY_FORGE

        if (moduleId !in ctx.profile.enabledModules) {
            return EngineExecutionResult(
                moduleId = moduleId,
                state = EngineExecutionState.SKIPPED,
                summary = "Disabled in active profile '${ctx.profile.name}'.",
            )
        }

        ctx.log("IntegrityForge", LogLevel.STAGE, "Computing DEX, Manifest, ARSC & Certificate SHA-256 baseline...")

        val dexDigests = linkedMapOf<String, String>()
        for ((dexName, bytes) in ctx.dexWorkingBytes) {
            dexDigests[dexName] = CryptoEngine.sha256Hex(bytes)
        }
        val manifestSha = ctx.manifestWorkingBytes?.let { CryptoEngine.sha256Hex(it) }
            ?: ctx.analysis.manifest.manifestSha256

        var arscSha = ctx.analysis.resourceBundle.arsc.arscSha256
        if (arscSha.isBlank()) {
            ZipFile(ctx.inputApk).use { zip ->
                zip.getEntry("resources.arsc")?.let { ze ->
                    arscSha = CryptoEngine.sha256Hex(zip.getInputStream(ze).use { it.readBytes() })
                }
            }
        }

        val certSha = ctx.credentials.profile.sha256Fingerprint
        val artifacts = mutableListOf<String>()

        if (ctx.profile.options.embedIntegrityManifest) {
            val seal = IntegritySealPayload(
                packageName = ctx.analysis.manifest.packageName,
                versionCode = ctx.analysis.manifest.versionCode,
                profileName = ctx.profile.name,
                createdAtMs = System.currentTimeMillis(),
                manifestSha256 = manifestSha,
                arscSha256 = arscSha,
                dexSha256Map = dexDigests,
                signingCertSha256 = certSha,
            )
            val sealBytes = json.encodeToString(seal).toByteArray(Charsets.UTF_8)
            ctx.addedZipEntries["assets/shieldforge_integrity.json"] = sealBytes
            artifacts.add("assets/shieldforge_integrity.json (${dexDigests.size} DEX digests + Manifest + ARSC)")
        }

        ctx.log(
            "IntegrityForge",
            LogLevel.VERIFIED,
            "Verified ${dexDigests.size} DEX digest(s) & signing cert ${certSha.take(16)}...",
        )

        return EngineExecutionResult(
            moduleId = moduleId,
            state = EngineExecutionState.SUCCEEDED,
            processedCount = dexDigests.size + 2,
            artifactsProduced = artifacts,
            summary = "Computed & sealed integrity baseline for ${dexDigests.size} DEX(es), Manifest, ARSC, and Signing Cert.",
            durationMs = System.currentTimeMillis() - start,
        )
    }

    fun generateSourceIntegrityGuardKotlin(
        packageName: String,
        expectedCertSha256: String,
    ): String = buildString {
        appendLine("package $packageName.security")
        appendLine()
        appendLine("import android.content.Context")
        appendLine("import android.content.pm.ApplicationInfo")
        appendLine("import android.content.pm.PackageManager")
        appendLine("import android.os.Build")
        appendLine("import java.security.MessageDigest")
        appendLine()
        appendLine("/**")
        appendLine(" * Generated by ShieldForge IntegrityForge (Mode B).")
        appendLine(" * Verifies signing certificate SHA-256 and debuggable flag at runtime.")
        appendLine(" */")
        appendLine("object IntegrityForgeGuard {")
        appendLine("    private const val EXPECTED_CERT_SHA256 = \"$expectedCertSha256\"")
        appendLine()
        appendLine("    fun verify(context: Context): Boolean {")
        appendLine("        val isDebuggable = (context.applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0")
        appendLine("        if (isDebuggable) return false")
        appendLine("        val pm = context.packageManager")
        appendLine("        val pkgInfo = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {")
        appendLine("            pm.getPackageInfo(context.packageName, PackageManager.GET_SIGNING_CERTIFICATES)")
        appendLine("        } else {")
        appendLine("            @Suppress(\"DEPRECATION\")")
        appendLine("            pm.getPackageInfo(context.packageName, PackageManager.GET_SIGNATURES)")
        appendLine("        }")
        appendLine("        val sigBytes = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {")
        appendLine("            pkgInfo.signingInfo?.apkContentsSigners?.firstOrNull()?.toByteArray()")
        appendLine("        } else {")
        appendLine("            @Suppress(\"DEPRECATION\")")
        appendLine("            pkgInfo.signatures?.firstOrNull()?.toByteArray()")
        appendLine("        } ?: return false")
        appendLine("        val sha256 = MessageDigest.getInstance(\"SHA-256\").digest(sigBytes)")
        appendLine("            .joinToString(\"\") { \"%02x\".format(it) }")
        appendLine("        return sha256.equals(EXPECTED_CERT_SHA256, ignoreCase = true)")
        appendLine("    }")
        appendLine("}")
    }
}
